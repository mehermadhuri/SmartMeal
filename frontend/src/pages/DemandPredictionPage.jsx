import { useEffect, useState } from 'react';
import { predictionAPI } from '../api/api';
import { Brain, RefreshCw, TrendingUp } from 'lucide-react';

export default function DemandPredictionPage() {
  const [predictions, setPredictions] = useState([]);
  const [loading, setLoading] = useState(true);
  const [generating, setGenerating] = useState(false);
  const [error, setError] = useState('');
  const [success, setSuccess] = useState('');

  useEffect(() => { loadPredictions(); }, []);

  const loadPredictions = async () => {
    setLoading(true);
    setError('');
    try {
      setPredictions(await predictionAPI.getAll() || []);
    } catch (err) {
      setError(err.message || 'Failed to load predictions');
    } finally {
      setLoading(false);
    }
  };

  const handleGenerate = async () => {
    setGenerating(true);
    setError('');
    setSuccess('');
    try {
      await predictionAPI.generate();
      setSuccess('Predictions refreshed successfully!');
      loadPredictions();
    } catch (err) {
      setError(err.message || 'Failed to generate predictions. AI service may not be running.');
    } finally {
      setGenerating(false);
    }
  };

  return (
    <div className="page">
      <div className="container">
        <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center', marginBottom: '1.5rem' }}>
          <div className="page-header" style={{ marginBottom: 0 }}>
            <h1><Brain size={28} /> AI Demand Predictions</h1>
            <p>Machine learning based meal demand forecasts for the canteen</p>
          </div>
          <button className="btn btn-primary" onClick={handleGenerate} disabled={generating}>
            <RefreshCw size={16} className={generating ? 'spin' : ''} /> {generating ? 'Generating...' : 'Refresh Predictions'}
          </button>
        </div>

        <div className="alert alert-info" style={{ marginBottom: '1.5rem' }}>
          <TrendingUp size={18} /> Predictions are generated by the Python AI service using historical booking patterns. Ensure the AI service is running on port 8000 for live predictions.
        </div>

        {error && <div className="alert alert-error">{error}</div>}
        {success && <div className="alert alert-success">{success}</div>}

        {loading ? <div className="spinner" /> : predictions.length === 0 ? (
          <div className="empty-state">
            <Brain size={56} />
            <h3>No predictions available</h3>
            <p>Click "Refresh Predictions" to generate demand forecasts using the AI service.</p>
          </div>
        ) : (
          <div className="table-container">
            <table>
              <thead>
                <tr><th>Menu Item</th><th>Meal Type</th><th>Predicted Demand</th><th>Recommended Qty</th><th>Prediction Date</th></tr>
              </thead>
              <tbody>
                {predictions.map(p => (
                  <tr key={p.id}>
                    <td style={{ fontWeight: 600 }}>{p.menuItem?.name || p.menuName || '—'}</td>
                    <td><span className="badge badge-primary">{p.mealType || p.menuItem?.category}</span></td>
                    <td>
                      <div style={{ display: 'flex', alignItems: 'center', gap: '0.5rem' }}>
                        <div style={{ background: 'var(--accent)', borderRadius: 4, height: 8, width: `${Math.min(100, (p.predictedQuantity || p.recommendedQuantity || 0) / 2)}%`, minWidth: 8 }} />
                        <strong>{p.predictedQuantity || p.recommendedQuantity || 0}</strong>
                      </div>
                    </td>
                    <td style={{ fontWeight: 700, color: 'var(--primary)' }}>{p.recommendedQuantity || p.predictedQuantity || '—'}</td>
                    <td style={{ fontSize: '0.82rem', color: 'var(--gray-500)' }}>
                      {p.predictionDate ? new Date(p.predictionDate).toLocaleDateString('en-IN') : new Date(p.createdAt).toLocaleDateString('en-IN')}
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        )}
      </div>
    </div>
  );
}
